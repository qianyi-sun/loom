"""Shared conversion helpers (benchmark integrations spec §5.3).

Every adapter funnels test/solution materialization through this module
so the on-disk layout (solution/, tests/, verifier/run.sh) stays
consistent across benchmarks. The util functions are intentionally
small and side-effect-only — adapters drive the logic; util writes the
files.
"""

from __future__ import annotations

import base64
import re
import textwrap
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import httpx
from loom_bundle_checksum import sha256_of_dir as sha256_of_dir

_IDENT_RE = re.compile(r"[^A-Za-z0-9_]")


def _slug(s: str) -> str:
    return _IDENT_RE.sub("_", s)[:64]


def pytest_from_test_strings(
    test_strings: list[str],
    *,
    out_dir: Path,
    prefix: str = "case",
) -> list[Path]:
    """Write one pytest file per assertion string.

    Each emitted file imports `from solution import *` so the adapter
    placing its solution under `solution/` can keep test code free of
    boilerplate. Test name is `test_{prefix}_{i}` so failures point at
    the upstream record index.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    slug = _slug(prefix)
    for i, body in enumerate(test_strings):
        target = out_dir / f"test_{slug}_{i}.py"
        target.write_text(
            textwrap.dedent(f"""
                # Auto-generated by loom_benchmarks.util.pytest_from_test_strings.
                from solution import *  # noqa: F401,F403


                def test_{slug}_{i}() -> None:
                    {body}
            """).strip()
            + "\n",
        )
        written.append(target)
    return written


def pytest_from_unittest(unittest_class_source: str, *, out_dir: Path) -> Path:
    """Drop a `unittest.TestCase` source verbatim — pytest collects it
    natively, so no wrapping is needed."""
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "test_upstream.py"
    body = (
        unittest_class_source
        if unittest_class_source.endswith("\n")
        else unittest_class_source + "\n"
    )
    target.write_text(body)
    return target


def structured_verifier_script(script_body: str, *, out_dir: Path) -> Path:
    """Write `verifier/run.sh`. The structured-verifier driver expects
    this exact relative path and the LOOM_VERIFIER_OUTPUT env var."""
    verifier_dir = out_dir / "verifier"
    verifier_dir.mkdir(parents=True, exist_ok=True)
    run_sh = verifier_dir / "run.sh"
    run_sh.write_text("#!/bin/sh\nset -e\n" + script_body + "\n")
    run_sh.chmod(0o755)
    return run_sh


_STUB_SOLUTION_BODY = '''"""Stub solution module — agents must overwrite this file.

Code-task bundles (HumanEval, MBPP, LiveCodeBench, ...) ship the
canonical upstream solution at `solution/_reference.py` and this
stub at `solution/solution.py`. The pytest verifier imports from
`solution.solution`, so any attempt to run the tests against this
stub fails loudly with NotImplementedError instead of silently
passing on the bundled reference answer.

- Non-oracle agents: must overwrite `solution.py` with their own
  attempt (the file the pytest tests import from).
- OracleAgent: `solve.sh` (written by `oracle_copy_reference_solve_script`)
  copies `_reference.py` over `solution.py` before the verifier runs,
  so oracle smoke trials still pass.
"""

def __getattr__(name: str):
    raise NotImplementedError(
        f"solution.solution.{name!r} not implemented — the agent must "
        f"replace this file with a real solution. Oracle agents do "
        f"this via solve.sh, which copies _reference.py."
    )
'''


def write_stub_solution_module(*, solution_dir: Path) -> Path:
    """Write the stub `solution/solution.py` next to a frozen
    `solution/_reference.py`. See `_STUB_SOLUTION_BODY` for the
    runtime contract."""
    solution_dir.mkdir(parents=True, exist_ok=True)
    stub = solution_dir / "solution.py"
    stub.write_text(_STUB_SOLUTION_BODY)
    return stub


def oracle_copy_reference_solve_script(
    *,
    solution_dir: Path,
    reference: str = "_reference.py",
    target: str = "solution.py",
) -> Path:
    """Write `solve.sh` that copies the bundled reference solution
    over the agent-editable target.

    For code-task bundles where the upstream reference is stored at
    `solution/_reference.py` and the agent-editable file is
    `solution/solution.py`. OracleAgent shells out to this script
    before the verifier runs, so oracle smoke still validates the
    full pipeline (without acting as a free pass for other agents
    that may not have written a real solution).

    Path note: OracleAgent runs the materialized script at
    `<workdir>/solution/solve.sh` with `cwd=<workdir>/solution`.
    Adapter unit tests may also invoke it as `bash solution/solve.sh`
    with `cwd=<tmp_path>`. The script probes both layouts and cds into
    whichever has the reference.
    """
    solution_dir.mkdir(parents=True, exist_ok=True)
    solve_sh = solution_dir / "solve.sh"
    solve_sh.write_text(
        "#!/bin/sh\n"
        "set -eu\n"
        'HERE="$(dirname "$0")"\n'
        f'if [ -f "$HERE/{reference}" ]; then\n'
        '    cd "$HERE"\n'
        f'elif [ -f "$HERE/solution/{reference}" ]; then\n'
        '    cd "$HERE/solution"\n'
        "else\n"
        f'    echo "solve.sh: cannot locate {reference} relative to $HERE" >&2\n'
        "    exit 1\n"
        "fi\n"
        f"cp -f {reference} {target}\n",
    )
    solve_sh.chmod(0o755)
    return solve_sh


def embed_base64_image(image_bytes: bytes, *, alt_text: str) -> str:
    """Inline a PNG/JPEG into instruction.md as a markdown image. Used
    by adapters whose upstream attaches screenshots inline (MMMU, GAIA
    multimodal subsets)."""
    if image_bytes[:8] == b"\x89PNG\r\n\x1a\n":
        mime = "image/png"
    elif image_bytes[:3] == b"\xff\xd8\xff":
        mime = "image/jpeg"
    else:
        mime = "application/octet-stream"
    payload = base64.b64encode(image_bytes).decode("ascii")
    return f"![{alt_text}](data:{mime};base64,{payload})"


def download_files_from_record(
    record: dict[str, Any],
    *,
    out_dir: Path,
    fields: tuple[str, ...],
) -> list[Path]:
    """For each name in `fields`, if `record[name]` is a non-empty URL,
    pull it into `out_dir` preserving the URL basename. Skips missing
    or empty fields so adapters can declare an optional-attachments
    superset and let upstream rows opt in by populating the field."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for field in fields:
        url = record.get(field)
        if not url:
            continue
        resp = httpx.get(url, timeout=30.0, follow_redirects=True)
        resp.raise_for_status()
        name = Path(urlparse(url).path).name or f"{field}.bin"
        target = out_dir / name
        target.write_bytes(resp.content)
        written.append(target)
    return written


def toml_string(value: str) -> str:
    """Render `value` as a TOML basic string literal (incl. quotes).

    Adapters that interpolate user-supplied or upstream-supplied data
    into `task.toml` should pass it through this helper instead of an
    f-string, so a `"` or `\\` or newline in an instance_id can't break
    the TOML document. Mirrors the TOML 1.0 escape table.
    """
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\b":
            out.append("\\b")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\f":
            out.append("\\f")
        elif ch == "\r":
            out.append("\\r")
        elif code < 0x20 or code == 0x7F:
            out.append(f"\\u{code:04X}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)
