"""Shared conversion helpers (benchmark integrations spec §5.3).

Every adapter funnels test/solution materialization through this module
so the on-disk layout (solution/, tests/, verifier/run.sh) stays
consistent across benchmarks. The util functions are intentionally
small and side-effect-only — adapters drive the logic; util writes the
files.
"""

from __future__ import annotations

import base64
import hashlib
import re
import textwrap
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import httpx

_IDENT_RE = re.compile(r"[^A-Za-z0-9_]")


def _slug(s: str) -> str:
    return _IDENT_RE.sub("_", s)[:64]


def pytest_from_test_strings(
    test_strings: list[str], *, out_dir: Path, prefix: str = "case",
) -> list[Path]:
    """Write one pytest file per assertion string.

    Each emitted file imports `from solution import *` so the adapter
    placing its solution under `solution/` can keep test code free of
    boilerplate. Test name is `test_{prefix}_{i}` so failures point at
    the upstream record index.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    slug = _slug(prefix)
    for i, body in enumerate(test_strings):
        target = out_dir / f"test_{slug}_{i}.py"
        target.write_text(
            textwrap.dedent(f"""
                # Auto-generated by loom_benchmarks.util.pytest_from_test_strings.
                from solution import *  # noqa: F401,F403


                def test_{slug}_{i}() -> None:
                    {body}
            """).strip() + "\n",
        )
        written.append(target)
    return written


def pytest_from_unittest(unittest_class_source: str, *, out_dir: Path) -> Path:
    """Drop a `unittest.TestCase` source verbatim — pytest collects it
    natively, so no wrapping is needed."""
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "test_upstream.py"
    body = (
        unittest_class_source
        if unittest_class_source.endswith("\n")
        else unittest_class_source + "\n"
    )
    target.write_text(body)
    return target


def structured_verifier_script(script_body: str, *, out_dir: Path) -> Path:
    """Write `verifier/run.sh`. The structured-verifier driver expects
    this exact relative path and the LOOM_VERIFIER_OUTPUT env var."""
    verifier_dir = out_dir / "verifier"
    verifier_dir.mkdir(parents=True, exist_ok=True)
    run_sh = verifier_dir / "run.sh"
    run_sh.write_text("#!/bin/sh\nset -e\n" + script_body + "\n")
    run_sh.chmod(0o755)
    return run_sh


def embed_base64_image(image_bytes: bytes, *, alt_text: str) -> str:
    """Inline a PNG/JPEG into instruction.md as a markdown image. Used
    by adapters whose upstream attaches screenshots inline (MMMU, GAIA
    multimodal subsets)."""
    if image_bytes[:8] == b"\x89PNG\r\n\x1a\n":
        mime = "image/png"
    elif image_bytes[:3] == b"\xff\xd8\xff":
        mime = "image/jpeg"
    else:
        mime = "application/octet-stream"
    payload = base64.b64encode(image_bytes).decode("ascii")
    return f"![{alt_text}](data:{mime};base64,{payload})"


def download_files_from_record(
    record: dict[str, Any], *, out_dir: Path, fields: tuple[str, ...],
) -> list[Path]:
    """For each name in `fields`, if `record[name]` is a non-empty URL,
    pull it into `out_dir` preserving the URL basename. Skips missing
    or empty fields so adapters can declare an optional-attachments
    superset and let upstream rows opt in by populating the field."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for field in fields:
        url = record.get(field)
        if not url:
            continue
        resp = httpx.get(url, timeout=30.0, follow_redirects=True)
        resp.raise_for_status()
        name = Path(urlparse(url).path).name or f"{field}.bin"
        target = out_dir / name
        target.write_bytes(resp.content)
        written.append(target)
    return written


def toml_string(value: str) -> str:
    """Render `value` as a TOML basic string literal (incl. quotes).

    Adapters that interpolate user-supplied or upstream-supplied data
    into `task.toml` should pass it through this helper instead of an
    f-string, so a `"` or `\\` or newline in an instance_id can't break
    the TOML document. Mirrors the TOML 1.0 escape table.
    """
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\b":
            out.append("\\b")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\f":
            out.append("\\f")
        elif ch == "\r":
            out.append("\\r")
        elif code < 0x20 or code == 0x7F:
            out.append(f"\\u{code:04X}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def sha256_of_dir(directory: Path) -> str:
    """Stable hash of (relpath, content) for every file under `directory`.

    The adapter writes this into `ConvertedTask.checksum`, which then
    populates `tasks.checksum`. Two converted dirs with identical
    content produce identical hashes; either content or relpath
    differing flips the digest."""
    h = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        if path.is_dir():
            continue
        rel = path.relative_to(directory).as_posix().encode("utf-8")
        h.update(b"\x00" + rel + b"\x00")
        h.update(path.read_bytes())
    return h.hexdigest()
