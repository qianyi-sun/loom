def test_rendered_settings_compiles_and_matches_snapshot(tmp_path: Path) -> None:
    """Round-trip: render → exec → assert model_fields match the
    pre-#146 snapshot. This is the migration safety net."""
    import json
    schema = load_schema(_REPO_SCHEMA)
    snapshot_dir = Path("tests/loom_config/snapshots")
    for svc, key, cls_name in [
        ("control-plane", "control_plane", "ControlPlaneSettings"),
        ("llm-gateway", "llm_gateway", "GatewaySettings"),
        ("loom-service", "loom_service", "LoomServiceSettings"),
        ("worker", "worker", "WorkerSettings"),
    ]:
        src = render_service_settings(schema, svc)
        ns: dict = {}
        exec(compile(src, f"<{svc}>", "exec"), ns)
        cls = ns[cls_name]
        actual = {
            name: {
                "annotation": str(f.annotation),
                "default": repr(f.default),
                "required": f.is_required(),
            }
            for name, f in cls.model_fields.items()
        }
        expected = json.loads((snapshot_dir / f"{key}.json").read_text())
        assert actual == expected, (
            f"{svc}: codegen output drifts from pre-#146 snapshot. "
            f"Diff missing fields: {set(expected) - set(actual)}, "
            f"extra fields: {set(actual) - set(expected)}"
        )


