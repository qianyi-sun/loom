"""Codegen: schema → `_generated.py` per service."""
from __future__ import annotations

from pathlib import Path

from loom_config.codegen import render_cluster_config_example, render_service_settings
from loom_config.loader import load_schema

_REPO_SCHEMA = Path("config/loom-schema.toml")


def test_renders_control_plane_with_all_field_kinds() -> None:
    schema = load_schema(_REPO_SCHEMA)
    src = render_service_settings(schema, "control-plane")
    assert "class ControlPlaneSettings(BaseSettings):" in src
    assert "step_jwt_signing_key: SecretStr" in src
    assert "admin_secret_file: Path | None = None" in src
    assert "bind_port: int = 8080" in src
    assert "AUTOGENERATED" in src


